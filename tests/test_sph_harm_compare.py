def _import_spherical():
  try:
    from jrystal.pseudopotential.spherical import (  # noqa: WPS433
      batch_sph_harm_real,
      cartesian_to_spherical,
    )
    return batch_sph_harm_real, cartesian_to_spherical
  except Exception:
    repo_root = Path(__file__).resolve().parents[1]
    sph_path = repo_root / "jrystal" / "pseudopotential" / "spherical.py"
    jrystal_path = repo_root / "jrystal"
    pseudo_path = jrystal_path / "pseudopotential"

    if "jrystal" not in sys.modules:
      jrystal_pkg = types.ModuleType("jrystal")
      jrystal_pkg.__path__ = [str(jrystal_path)]
      sys.modules["jrystal"] = jrystal_pkg
    if "jrystal.pseudopotential" not in sys.modules:
      pseudo_pkg = types.ModuleType("jrystal.pseudopotential")
      pseudo_pkg.__path__ = [str(pseudo_path)]
      sys.modules["jrystal.pseudopotential"] = pseudo_pkg

    spec = importlib.util.spec_from_file_location(
      "jrystal.pseudopotential.spherical",
      sph_path,
    )
    if spec is None or spec.loader is None:
      raise ImportError(f"Unable to load {sph_path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module.batch_sph_harm_real, module.cartesian_to_spherical


def main() -> None:
  batch_sph_harm_real, cartesian_to_spherical = _import_spherical()
  r_av = R_AV
  gpaw_vals = Y_MA

  r = np.linalg.norm(r_av, axis=1)
  r = np.where(r < 1e-6, 1e-6, r)

  # GPAW L -> (l, m) mapping for L=0..8.
  l_list = np.array([0, 1, 1, 1, 2, 2, 2, 2, 2], dtype=int)
  m_list = np.array([0, -1, 0, 1, -2, -1, 0, 1, 2], dtype=int)
  L_list = np.arange(len(l_list), dtype=int)

  # Jrystal real harmonics are angular; convert to solid by r^l.
  sph = cartesian_to_spherical(r_av)
  theta = np.asarray(sph[:, 1])
  phi = np.asarray(sph[:, 2])

  for L, l, m in zip(L_list, l_list, m_list):
    y_real = np.asarray(batch_sph_harm_real(int(l), theta, phi))
    y_lm = y_real[:, m + l]
    y_solid = y_lm * (r ** l)
    ratio = gpaw_vals[L] / y_solid
    ratio_mean = float(np.mean(ratio))
    max_rel = float(np.max(np.abs(ratio - ratio_mean)) /
                    (abs(ratio_mean) + 1e-12))
    if max_rel > 1e-6:
      raise AssertionError(
        f"L={L} l={l} m={m} max_rel={max_rel:.3e} exceeds tolerance"
      )


if __name__ == "__main__":
  main()
